    <h4 class="mt-4">What is a Memory Foam Mattress?</h4>
    <p>
        A memory foam mattress is made from viscoelastic foam that adapts to your body shape. It responds to heat and pressure, allowing it to contour perfectly to your body.
    </p>
    <p>
        This type of mattress is known for providing a “hug-like” feeling, which helps distribute body weight evenly and reduces pressure points.
    </p>

