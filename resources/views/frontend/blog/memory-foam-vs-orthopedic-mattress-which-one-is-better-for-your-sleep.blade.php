        <li>Absorbs motion (ideal for couples)</li>
        <li>Provides soft to medium firmness</li>
    </ul>

    <h4 class="mt-4">What is an Orthopedic Mattress?</h4>
    <p>
        An orthopedic mattress is specifically designed to support the spine, joints, and overall body posture. It is often recommended by doctors for people suffering from back pain or posture-related issues.
    </p>
    <p>
        These mattresses are usually firmer and provide targeted support to maintain proper spinal alignment.
