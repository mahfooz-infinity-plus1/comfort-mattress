                        <p class="mb-2">A mattress is a long-term purchase, so after-sales support matters.</p>
                        <p class="mb-2">Before purchasing, check:</p>
                        <ul class="ms-4">
                            <li class="mb-2">Warranty duration</li>
                            <li class="mb-2">What the warranty covers</li>
                            <li class="mb-2">Warranty exclusions</li>
                            <li class="mb-2">Replacement or repair policies</li>
                            <li class="mb-2">Customer support process</li>
                            <li class="mb-2">Care and maintenance instructions</li>
                        </ul>
                        <p class="mb-2">A clear warranty policy gives you a better understanding of the manufacturer's commitment to the product.</p>
                        <p class="mb-2">Avoid choosing a mattress solely because it has the longest warranty. The actual terms and conditions are more important than the number of years advertised.</p>

