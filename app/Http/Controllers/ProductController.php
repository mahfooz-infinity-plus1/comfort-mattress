<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use App\Services\MattressPriceImportService;

class ProductController extends Controller
{

public function showImportForm()
{
    return view('import-mattress-prices');
}
    /*
    |--------------------------------------------------------------------------
    | Import Mattress Prices CSV
    |--------------------------------------------------------------------------
    */

    public function importMattressPrices(
        Request $request,
        MattressPriceImportService $service
    ) {

        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        $request->validate([
            'file'       => 'required|mimes:csv,txt',
            'product_id' => 'required|integer',
        ]);

        /*
        |--------------------------------------------------------------------------
        | Get Uploaded File
        |--------------------------------------------------------------------------
        */

        $path = $request->file('file')->getRealPath();

        $rows = [];

        /*
        |--------------------------------------------------------------------------
        | Open CSV
        |--------------------------------------------------------------------------
        */

        if (($handle = fopen($path, 'r')) !== false) {

            /*
            |--------------------------------------------------------------------------
            | First Row = Header
            |--------------------------------------------------------------------------
            |
            | Example:
            |
            | Dimension,5",6",8"
            |
            */

            $header = fgetcsv($handle);

            /*
            |--------------------------------------------------------------------------
            | Process Rows
            |--------------------------------------------------------------------------
            */

            while (($data = fgetcsv($handle)) !== false) {

                /*
                |--------------------------------------------------------------------------
                | Skip Empty Rows
                |--------------------------------------------------------------------------
                */

                if (empty($data[0])) {
                    continue;
                }

                $prices = [];

                /*
                |--------------------------------------------------------------------------
                | Thickness Columns
                |--------------------------------------------------------------------------
                */

                foreach ($header as $index => $column) {

                    /*
                    |--------------------------------------------------------------------------
                    | Skip First Column
                    |--------------------------------------------------------------------------
                    */

                    if ($index == 0) {
                        continue;
                    }

                    $prices[$column] = isset($data[$index])
                        ? $data[$index]
                        : null;
                }

                /*
                |--------------------------------------------------------------------------
                | Final Row Structure
                |--------------------------------------------------------------------------
                */

                $rows[] = [
                    'dimension' => $data[0],
                    'prices'    => $prices,
                ];
            }

            fclose($handle);
        }

        /*
        |--------------------------------------------------------------------------
        | Import Service
        |--------------------------------------------------------------------------
        */

        $report = $service->import(
            $rows,
            $request->product_id
        );

        /*
        |--------------------------------------------------------------------------
        | Response
        |--------------------------------------------------------------------------
        */

        return view(
            'import-report',
            compact('report')
        );

        // return response()->json([
        //     'success' => true,
        //     'message' => 'Mattress prices imported successfully',
        // ]);
    }
}
